#!/usr/bin/env node
/**
 * Fetches TweakCN theme JSON and emits src/styles/themes.generated.css
 * Run: node scripts/generate-theme-css.mjs
 *
 * Emits color tokens only. Radius, fonts, shadows, and spacing stay in globals.css
 * (cyberpunk defaults) and are not taken from TweakCN exports.
 */

import { mkdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUT = join(__dirname, "../src/styles/themes.generated.css")

/** Preset themes use slug; community themes use registryId (tweakcn.com/themes/{id}). */
