const themeSourceUrl = (theme) => {
  if (theme.registryId) {
    return `https://tweakcn.com/themes/${theme.registryId}`
  }
  return `https://tweakcn.com/r/themes/${theme.slug}.json`
}

const fetchTheme = async (theme) => {
  const candidates = theme.registryId
    ? [`https://tweakcn.com/r/themes/${theme.registryId}`]
    : [
        `https://tweakcn.com/r/themes/${theme.slug}.json`,
        `https://tweakcn.com/r/themes/${theme.slug}`,
      ]

  let lastError
  for (const url of candidates) {
    const res = await fetch(url)
    if (!res.ok) {
      lastError = new Error(`${url}: HTTP ${res.status}`)
      continue
    }
    return res.json()
  }
  throw lastError ?? new Error("No fetch URL")
}

const emitVars = (vars, indent = "  ") => {
  const lines = []
  for (const key of SHADCN_KEYS) {
    if (vars[key]) lines.push(`${indent}--${key}: ${vars[key]};`)
  }
  return lines.join("\n")
}

const main = async () => {
  const blocks = [
    "/* Auto-generated by scripts/generate-theme-css.mjs — do not edit by hand */",
    "",
  ]
  const registry = []

  for (const theme of THEMES) {
    let data
    try {
      data = await fetchTheme(theme)
    } catch (e) {
      const ref = theme.registryId ?? theme.slug
      console.error(`Skip ${theme.id} (${ref}):`, e.message)
      continue
    }

    const dark = data.cssVars?.dark ?? data.cssVars?.theme ?? {}
    const primary = dark.primary ?? "oklch(0.72 0.2 280)"
    const accent = dark.accent ?? primary

    blocks.push(`/* ${theme.label} — ${themeSourceUrl(theme)} */`)
    blocks.push(`html.dark[data-theme="${theme.id}"] {`)
    blocks.push(emitVars(dark))
    blocks.push(
      `  --grid-line: color-mix(in oklch, ${primary} 12%, transparent);`,
      `  --neon-glow: color-mix(in oklch, ${primary} 35%, transparent);`,
      `  --neon-glow-accent: color-mix(in oklch, ${accent} 28%, transparent);`,
      "}",
      ""
    )

    registry.push({
      id: theme.id,
      label: theme.label,
      ...(theme.slug ? { slug: theme.slug } : {}),
      ...(theme.registryId ? { registryId: theme.registryId } : {}),
      primary: dark.primary,
      accent: dark.accent,
    })
    const ref = theme.registryId ?? theme.slug
    console.log(`OK ${theme.id} <- ${ref} (${data.name ?? theme.label})`)
  }

  mkdirSync(dirname(OUT), { recursive: true })
  mkdirSync(join(__dirname, "../src/lib/theme"), { recursive: true })
  writeFileSync(OUT, blocks.join("\n"))
  writeFileSync(
    join(__dirname, "../src/lib/theme/theme-registry.json"),
    JSON.stringify(registry, null, 2)
  )
  console.log(`Wrote ${OUT}`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
